// This will be populated after running the upload script
// For now, using placeholder URLs that will be replaced with actual Blob URLs
export const BLOB_VIDEO_BASE_URL = process.env.NEXT_PUBLIC_BLOB_URL || '';

// Helper function to get video URL
export const getBlobVideoUrl = (fileName: string): string => {
  // In production, this will use the actual Blob URLs
  // For development, fall back to local files
  if (BLOB_VIDEO_BASE_URL) {
    return `${BLOB_VIDEO_BASE_URL}/videos/${fileName}`;
  }
  
  // Fallback to local files during development
  return `/videos/full/${fileName}`;
};

