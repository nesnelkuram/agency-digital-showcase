// Dynamic import of blob URLs (generated by upload script)
export const loadBlobUrls = async () => {
  try {
    const blobUrls = await import('./blob-urls.json');
    return blobUrls.default;
  } catch (error) {
    console.warn('Blob URLs not found, using fallback URLs');
    return {};
  }
};